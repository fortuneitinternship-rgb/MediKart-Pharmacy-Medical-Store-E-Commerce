-- ==============================
-- SAFE USER DATA VIEW
-- ==============================
-- Never expose hashed_password, otp, or otp_expires_at to the frontend.
CREATE OR REPLACE VIEW user_account_data AS
SELECT
  id,
  name,
  email,
  phone,
  is_active,
  is_verified,
  is_admin,
  created_at
FROM users;
